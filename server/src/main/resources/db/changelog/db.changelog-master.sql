FROM T_CHANGE_STAGED s
INNER JOIN T_CHANGE_PAYLOAD p
  ON p.CHANGE_PAYLOAD_ID = s.CHANGE_PAYLOAD_ID
INNER JOIN T_CHANGE_ACTION_STATUS cas
  ON cas.ACTION = s.ACTION
 AND cas.STAGE = 'STAGED'
INNER JOIN T_ASSET_TYPE_HISTORY ath
  ON ath.ASSET_TYPE_ID = s.ASSET_TYPE_ID
 AND ath.VALID_TO IS NULL
UNION ALL
SELECT
  c.CHANGE_ID AS CHANGE_ID,
  'COMMITTED' AS STAGE,
  cas.STATUS AS STATUS_LABEL,
