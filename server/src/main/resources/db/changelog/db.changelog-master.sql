  (SELECT MIN(si.CHANGE_SPEC_ID) FROM T_CHANGE_SPEC_ITEM si WHERE si.CHANGE_ID = u.CHANGE_ID) AS CHANGE_SPEC_ID
FROM T_CHANGE_UNTRACKED u
INNER JOIN T_CHANGE_PAYLOAD p
  ON p.CHANGE_PAYLOAD_ID = u.CHANGE_PAYLOAD_ID
INNER JOIN T_CHANGE_ACTION_STATUS cas
