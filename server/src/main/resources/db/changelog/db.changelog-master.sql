 AND cas.STAGE = 'UNTRACKED'
UNION ALL
SELECT
  s.CHANGE_ID AS CHANGE_ID,
  'STAGED' AS STAGE,
  cas.STATUS AS STATUS_LABEL,
  p.BODY AS BODY,
  s.ASSET_TYPE_ID AS ASSET_TYPE_ID,
